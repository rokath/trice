package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type tilEntry struct {
	Type string `json:"Type"`
	Strg string `json:"Strg"`
}

type liEntry struct {
	File string `json:"File"`
	Path string `json:"Path"`
	Line int    `json:"Line"`
}

type binding struct {
	ID   int
	Line int
	TIL  tilEntry
}

func main() {
	if len(os.Args) < 2 || os.Args[1] != "bind" {
		fmt.Fprintln(os.Stderr, "usage: trice bind -til til.json -li li.json -src file.c -out file.c.triceIDs.h")
		os.Exit(2)
	}

	bindFlags := flag.NewFlagSet("bind", flag.ExitOnError)
	tilName := bindFlags.String("til", "til.json", "Trice ID list")
	liName := bindFlags.String("li", "li.json", "Trice location information")
	srcName := bindFlags.String("src", "", "source file to bind")
	outName := bindFlags.String("out", "", "generated sidecar header")
	if err := bindFlags.Parse(os.Args[2:]); err != nil {
		fail(err)
	}

	if *srcName == "" || *outName == "" {
		fail(errors.New("-src and -out are required"))
	}

	var til map[string]tilEntry
	readJSON(*tilName, &til)

	var li map[string]liEntry
	readJSON(*liName, &li)

	normalizedSource := normalize(*srcName)
	sourceBytes, err := os.ReadFile(*srcName)
	if err != nil {
		fail(err)
	}
	sourceLines := strings.Split(string(sourceBytes), "\n")

	var bindings []binding
	usedLines := map[int]int{}
	for idText, loc := range li {
		locPath := loc.Path
		if locPath == "" {
			locPath = loc.File
		}
		if loc.Path != "" {
			if normalize(loc.Path) != normalizedSource {
				continue
			}
		} else if filepath.Base(loc.File) != filepath.Base(normalizedSource) {
			continue
		}

		id, err := strconv.Atoi(idText)
		if err != nil || id <= 0 || id > 0x3FFF {
			fail(fmt.Errorf("invalid 14-bit Trice ID %q", idText))
		}
		info, ok := til[idText]
		if !ok {
			fail(fmt.Errorf("ID %s is present in li.json but missing in til.json", idText))
		}
		if info.Type != "trice" {
			fail(fmt.Errorf("ID %s has type %q; this PoC supports type trice", idText, info.Type))
		}
		if loc.Line < 1 || loc.Line > len(sourceLines) {
			fail(fmt.Errorf("ID %s references invalid line %d", idText, loc.Line))
		}
		if previous, exists := usedLines[loc.Line]; exists {
			fail(fmt.Errorf("IDs %d and %d share source line %d", previous, id, loc.Line))
		}

		line := sourceLines[loc.Line-1]
		quotedFormat := strconv.Quote(info.Strg)
		if !strings.Contains(line, "trice(") || !strings.Contains(line, quotedFormat) {
			fail(fmt.Errorf("%s:%d does not contain trice(%s)", *srcName, loc.Line, quotedFormat))
		}

		usedLines[loc.Line] = id
		bindings = append(bindings, binding{ID: id, Line: loc.Line, TIL: info})
	}

	if len(bindings) == 0 {
		fail(fmt.Errorf("no locations in %s match %s", *liName, *srcName))
	}
	sort.Slice(bindings, func(i, j int) bool { return bindings[i].Line < bindings[j].Line })

	if err := os.MkdirAll(filepath.Dir(*outName), 0o755); err != nil {
		fail(err)
	}

	guard := strings.ToUpper(filepath.Base(*outName))
	replacer := strings.NewReplacer(".", "_", "-", "_", " ", "_")
	guard = replacer.Replace(guard) + "_"

	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by trice bind. Do not edit.\n")
	fmt.Fprintf(&b, "#ifndef %s\n#define %s\n\n", guard, guard)
	for _, item := range bindings {
		fmt.Fprintf(&b, "// ID %d: %s", item.ID, item.TIL.Strg)
		if !strings.HasSuffix(item.TIL.Strg, "\n") {
			b.WriteByte('\n')
		}
		fmt.Fprintf(&b, "#define TRICE_ID_L%d %du\n\n", item.Line, item.ID)
	}
	fmt.Fprintf(&b, "#endif\n")

	if err := writeIfChanged(*outName, []byte(b.String())); err != nil {
		fail(err)
	}
	fmt.Printf("generated %s with %d binding(s)\n", *outName, len(bindings))
}

func normalize(name string) string {
	clean := filepath.Clean(name)
	clean = filepath.ToSlash(clean)
	return strings.TrimPrefix(clean, "./")
}

func readJSON(name string, dst any) {
	data, err := os.ReadFile(name)
	if err != nil {
		fail(err)
	}
	if err := json.Unmarshal(data, dst); err != nil {
		fail(fmt.Errorf("%s: %w", name, err))
	}
}

func writeIfChanged(name string, data []byte) error {
	old, err := os.ReadFile(name)
	if err == nil && string(old) == string(data) {
		return nil
	}
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	temp := name + ".tmp"
	if err := os.WriteFile(temp, data, 0o644); err != nil {
		return err
	}
	return os.Rename(temp, name)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "trice-bind:", err)
	os.Exit(1)
}
